// Run only against the disposable QA server described in docs/tutorial-07.md.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const base = process.env.QA_URL || 'http://127.0.0.1:8007';
const password = process.env.QA_PASSWORD || 'temporary-browser-qa';
const checks = [];
function check(condition, label) { assert(condition, label); checks.push(label); }
(async () => {
 const browser = await chromium.launch({headless:true, executablePath:process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
 try {
 const context = await browser.newContext({viewport:{width:1440,height:1000}});
 const page = await context.newPage();
 const errors=[]; const calls=[];
 page.on('pageerror', e=>errors.push(e.message));
 page.on('request', r=>calls.push({url:r.url(),method:r.method(),type:r.resourceType()}));
 await page.goto(base+'/project/');
 await page.waitForSelector('#grid .project-card');
 check(calls.some(r=>r.url.includes('/api/v1/projects/')), 'Projects reads the DRF list');
 check(await page.locator('.button-star').first().textContent().then(s=>s.includes('Login to star')), 'Guests are asked to login to star');
 check(await page.locator('.project-add-button').count()===0,'Guests cannot add projects');
 await page.getByRole('link',{name:'Experience',exact:true}).hover();
 check(await page.getByRole('link',{name:'Experience',exact:true}).evaluate(el=>el.matches(':hover')), 'Card overlay does not steal navbar hover');
 await page.locator('.project-title-button').first().click();
 check(await page.locator('#project-detail-modal').evaluate(el=>el.open),'Detail popup opens');
 const position = await page.evaluate(()=>scrollY);
 for(let i=0;i<5;i++) await page.keyboard.press('Tab');
 check(await page.evaluate(()=>document.activeElement.closest('#project-detail-modal')!==null),'Popup traps keyboard focus');
 await page.keyboard.press('Escape');
 check(await page.locator('dialog[open]').count()===0,'Escape closes the popup');
 check(await page.evaluate(()=>location.hash===''&&scrollY===0),'Closing popup preserves page position and URL');
 await page.locator('label[for=tab-design]').click();
 await page.locator('label[for=tab-all]').click();
 const input=page.locator('#search-input');
 const before=calls.filter(r=>r.url.includes('/api/v1/projects/')&&r.method==='GET').length;
 await input.pressSequentially('nothing-matches-qa',{delay:15});
 await page.waitForSelector('#empty:not(.hide)');
 const after=calls.filter(r=>r.url.includes('/api/v1/projects/')&&r.method==='GET').length;
 check(after-before===1,'Search debounces keystrokes into one GET');
 await page.route('**/api/v1/projects/**',route=>route.abort());
 await input.fill('offline'); await input.press('Enter');
 await page.waitForSelector('#error:not(.hide)');
 check(true,'Network failure shows error state');
 await page.unroute('**/api/v1/projects/**');
 await input.fill(''); await page.locator('#project-retry').click();
 await page.waitForSelector('#grid .project-card');
 check(true,'Retry recovers from a failed GET');
 await page.goto(base+'/login/');
 await page.locator('#id_username').fill('qa-owner'); await page.locator('#id_password').fill(password);
 await page.getByRole('button',{name:'Login',exact:true}).click();
 await page.waitForURL(base+'/');
 await page.goto(base+'/project/'); await page.waitForSelector('#grid .project-card');
 const docsBefore=calls.filter(r=>r.type==='document').length;
 const title='QA Project '+Date.now();
 await page.locator('[data-new-project]').click();
 for(const [name,value] of Object.entries({title,category:'design',image_url:'/static/img/monte.png',short_description:'Short QA',full_description:'<img src=x onerror="window.qaXss=1"> Full QA',tags:'Django, QA'})) await page.locator('#project-form [name="'+name+'"]').fill(value);
 await page.locator('#project-form button[type=submit]').click();
 await page.waitForFunction(t=>[...document.querySelectorAll('.project-title-button')].some(el=>el.textContent===t),title);
 check(calls.some(r=>r.method==='POST'&&r.url.endsWith('/api/v1/projects/')),'Create uses JSON POST to DRF');
 check(!await page.evaluate(()=>window.qaXss),'HTML input does not execute');
 let card=page.locator('.project-card').filter({has:page.getByRole('button',{name:title,exact:true})});
 await card.locator('[data-action=edit]').click();
 await page.locator('#project-form [name=title]').fill(title+' Edited');
 await page.locator('#project-form button[type=submit]').click();
 await page.waitForFunction(t=>[...document.querySelectorAll('.project-title-button')].some(el=>el.textContent===t),title+' Edited');
 check(calls.some(r=>r.method==='PATCH'&&r.url.includes('/api/v1/projects/')),'Edit uses PATCH and refreshes');
 card=page.locator('.project-card').filter({has:page.getByRole('button',{name:title+' Edited',exact:true})});
 await card.locator('[data-action=star]').click();
 await page.waitForFunction(t=>[...document.querySelectorAll('.project-card')].find(c=>c.textContent.includes(t))?.querySelector('[data-action=star]')?.getAttribute('aria-pressed')==='true',title);
 check(true,'Star updates without reload');
 card=page.locator('.project-card').filter({has:page.getByRole('button',{name:title+' Edited',exact:true})});
 await card.locator('[data-action=star]').click();
 await page.waitForFunction(t=>[...document.querySelectorAll('.project-card')].find(c=>c.textContent.includes(t))?.querySelector('[data-action=star]')?.getAttribute('aria-pressed')==='false',title);
 await card.locator('[data-action=delete]').click();
 await page.locator('#delete-confirmation [data-dialog-close]').last().click();
 check(await card.count()===1,'Cancel preserves project');
 await card.locator('[data-action=delete]').click();
 await page.locator('#delete-confirmation button[type=submit]').click();
 await page.waitForFunction(t=>![...document.querySelectorAll('.project-title-button')].some(el=>el.textContent.includes(t)),title);
 check(calls.some(r=>r.method==='DELETE'&&r.url.includes('/api/v1/projects/')),'Delete uses DELETE and refreshes');
 check(calls.filter(r=>r.type==='document').length===docsBefore,'CRUD and stars do not reload the document');
 // Validation messages keep the form and entered values visible.
 await page.locator('[data-new-project]').click();
 for(const [name,value] of Object.entries({title:'<b></b>',category:'design',image_url:'/static/img/monte.png',short_description:'Short',full_description:'Full',tags:'QA'})) await page.locator('#project-form [name="'+name+'"]').fill(value);
 await page.locator('#project-form button[type=submit]').click();
 await page.waitForFunction(()=>document.querySelector('#toast-title')?.textContent==='Could not save project');
 check(await page.locator('#add-project-modal').evaluate(el=>el.open),'Invalid data keeps the modal open');
 await page.keyboard.press('Escape');
 await page.goto(base+'/experience/'); await page.waitForSelector('#experience-list .timeline-item');
 await page.locator('[data-new-experience]').click();
 const expTitle='QA Experience '+Date.now();
 for(const [name,value] of Object.entries({title:expTitle,location:'UI',started_at:'2026-09-01',description:'QA experience'})) await page.locator('#experience-form [name="'+name+'"]').fill(value);
 await page.locator('#experience-form [name=category]').selectOption('research');
 await page.locator('#experience-form button[type=submit]').click();
 await page.waitForFunction(t=>document.querySelector('#experience-list').textContent.includes(t),expTitle);
 let exp=page.locator('.timeline-item').filter({hasText:expTitle}); await exp.locator('summary').click();
 await exp.locator('[data-action=edit]').click(); await page.locator('#experience-form [name=ended_at]').fill('2026-08-01');
 await page.locator('#experience-form button[type=submit]').click();
 await page.waitForFunction(()=>document.querySelector('#toast-message')?.textContent.includes('End date'));
 check(await page.locator('#add-experience-modal').evaluate(el=>el.open),'Reversed dates show validation and retain form');
 await page.locator('#experience-form [name=ended_at]').fill('2026-10-01'); await page.locator('#experience-form button[type=submit]').click();
 await page.waitForFunction(()=>!document.getElementById('add-experience-modal').open);
 await page.waitForFunction(t=>document.querySelector('#experience-list').textContent.includes(t),expTitle);
 exp=page.locator('.timeline-item').filter({hasText:expTitle});
 if(!await exp.evaluate(el=>el.open)) await exp.locator('summary').click();
 await exp.locator('[data-action=delete]').click(); await page.locator('#delete-confirmation button[type=submit]').click();
 await page.waitForFunction(t=>!document.querySelector('#experience-list').textContent.includes(t),expTitle);
 check(true,'Experience create, update and delete use AJAX');
 // Isolated Editor session.
 const editorContext=await browser.newContext(); const editor=await editorContext.newPage();
 await editor.goto(base+'/login/'); await editor.locator('#id_username').fill('qa-editor'); await editor.locator('#id_password').fill(password);
 await editor.getByRole('button',{name:'Login',exact:true}).click(); await editor.waitForURL(base+'/');
 await editor.goto(base+'/experience/'); await editor.waitForSelector('.timeline-item');
 check(await editor.locator('[data-new-experience]').count()===0,'Editor cannot see create control');
 const first=editor.locator('.timeline-item').first(); await first.locator('summary').click();
 check(await first.locator('[data-action=delete]').count()===0,'Editor cannot see delete control');
 await first.locator('[data-action=edit]').click(); await editor.locator('#experience-form button[type=submit]').click();
 await editor.waitForFunction(()=>!document.getElementById('add-experience-modal').open);
 check(true,'Editor can update Experience via modal');
 await editor.goto(base+'/project/'); await editor.waitForSelector('.project-card');
 check(await editor.locator('[data-action=edit]').count()===0,'Projects API UI reserves editing for owner');
 const visitorContext=await browser.newContext(); const visitor=await visitorContext.newPage();
 await visitor.goto(base+'/login/?next=/project/'); await visitor.locator('#id_username').fill('qa-visitor'); await visitor.locator('#id_password').fill(password);
 await visitor.getByRole('button',{name:'Login',exact:true}).click(); await visitor.waitForURL(base+'/project/'); await visitor.waitForSelector('.project-card');
 check(await visitor.locator('[data-action=edit], [data-action=delete], [data-new-project]').count()===0,'Ordinary account cannot manage Projects');
 const visitorStar=visitor.locator('[data-action=star]').first();
 const pressed=await visitorStar.getAttribute('aria-pressed');
 await visitorStar.click(); await visitor.waitForFunction(old=>document.querySelector('[data-action=star]')?.getAttribute('aria-pressed')!==old,pressed);
 check(true,'Ordinary account can star with session and CSRF');
 await visitor.locator('[data-action=star]').first().click();
 await visitor.waitForFunction(old=>document.querySelector('[data-action=star]')?.getAttribute('aria-pressed')===old,pressed);
 await visitor.goto(base+'/experience/'); await visitor.waitForSelector('.timeline-item');
 const visitorExperience=visitor.locator('.timeline-item').first(); await visitorExperience.locator('summary').click();
 const experiencePressed=await visitorExperience.locator('[data-action=star]').getAttribute('aria-pressed');
 await visitorExperience.locator('[data-action=star]').click();
 await visitor.waitForFunction(old=>document.querySelector('.timeline-item [data-action=star]')?.getAttribute('aria-pressed')!==old,experiencePressed);
 check(true,'Ordinary account can star Experience through DRF');
 check(await visitor.locator('.timeline-item').first().evaluate(el=>el.open),'Experience expansion survives a star refresh');
 await visitor.locator('.timeline-item [data-action=star]').first().click();
 await visitor.waitForFunction(old=>document.querySelector('.timeline-item [data-action=star]')?.getAttribute('aria-pressed')===old,experiencePressed);

 // Mobile layout + dark theme + popup.
 await page.setViewportSize({width:390,height:844}); await page.goto(base+'/project/'); await page.waitForSelector('.project-card');
 await page.locator('label[for=theme-toggle]').click();
 await page.locator('.project-title-button').first().click();
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile page has no horizontal overflow');
 check(await page.locator('#project-detail-modal .project-form-modal__content').evaluate(el=>el.getBoundingClientRect().width<=innerWidth),'Mobile popup fits viewport');
 check(await page.locator('#project-detail-modal .project-form-modal__content').evaluate(el=>{const r=el.getBoundingClientRect();return r.top>=0&&r.bottom<=innerHeight+1;}),'Mobile popup stays vertically within viewport');
 await page.screenshot({path:'/tmp/myportofolio-mobile.png'});
 await page.keyboard.press('Escape');
 await page.goto(base+'/');
 check(await page.locator('#theme-toggle').isChecked(),'Dark theme persists across navigation');
 await page.locator('label[for=nav-toggle]').click();
 check(await page.locator('#nav-toggle').isChecked(),'Mobile menu opens');
 await page.keyboard.press('Escape');
 check(!await page.locator('#nav-toggle').isChecked(),'Escape closes mobile menu');
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile homepage has no horizontal overflow');
 await page.screenshot({path:'/tmp/myportofolio-home-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000}); await page.goto(base+'/project/'); await page.waitForSelector('.project-card');
 await page.screenshot({path:'/tmp/myportofolio-projects-desktop.png',fullPage:true});
 check(errors.length===0,'No JavaScript runtime errors: '+errors.join(', '));
 console.log(JSON.stringify({passed:checks.length,checks},null,2));
 } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
